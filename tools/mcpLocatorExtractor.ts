/**
 * MCP-Driven Locator Extractor
 *
 * Uses Playwright to navigate to the QA app, inspect the DOM, and extract
 * all interactive elements as structured locators. Outputs a TypeScript
 * locator file compatible with the existing POM framework.
 *
 * Usage:
 *   npx ts-node tools/mcpLocatorExtractor.ts --url <page-url> --output <locator-file-name>
 *
 * Example:
 *   npx ts-node tools/mcpLocatorExtractor.ts --url "https://lqatms-test5.ptcnet.ptc.com/QALink/jsp/home/" --output homePage
 */

import { chromium, Page } from "@playwright/test";
import fs from "fs";
import path from "path";

interface ExtractedLocator {
  name: string;
  selector: string;
  type: string;
  text?: string;
  attributes: Record<string, string>;
}

/** Extracts all interactive elements from a page's DOM */
async function extractLocatorsFromPage(
  page: Page,
): Promise<ExtractedLocator[]> {
  return page.evaluate(() => {
    const interactiveSelectors = [
      "a[href]",
      "button",
      "input",
      "select",
      "textarea",
      "table",
      "[role='button']",
      "[role='tab']",
      "[role='link']",
      "[role='menuitem']",
      "[onclick]",
      "img[alt]",
    ];

    const seen = new Set<string>();
    const results: ExtractedLocator[] = [];

    for (const selector of interactiveSelectors) {
      const elements = document.querySelectorAll(selector);

      elements.forEach((el) => {
        const tag = el.tagName.toLowerCase();
        const id = el.getAttribute("id");
        const name = el.getAttribute("name");
        const type = el.getAttribute("type") || "";
        const text = (el.textContent || "").trim().substring(0, 80);
        const role = el.getAttribute("role") || "";
        const alt = el.getAttribute("alt") || "";
        const className = el.getAttribute("class") || "";
        const href = el.getAttribute("href") || "";
        const value = el.getAttribute("value") || "";

        // Build the best selector
        let bestSelector = "";
        let locatorName = "";

        if (id) {
          bestSelector = `#${id}`;
          locatorName = camelCase(id);
        } else if (name) {
          bestSelector = `${tag}[name="${name}"]`;
          locatorName = camelCase(name);
        } else if (alt) {
          bestSelector = `${tag}[alt="${alt}"]`;
          locatorName = camelCase(alt.substring(0, 40));
        } else if (text && text.length < 50) {
          bestSelector = `${tag}:has-text("${text.substring(0, 40)}")`;
          locatorName = camelCase(text.substring(0, 40));
        } else if (value) {
          bestSelector = `${tag}[value="${value}"]`;
          locatorName = camelCase(value.substring(0, 40));
        } else if (className) {
          const firstClass = className.split(" ")[0];
          bestSelector = `${tag}.${firstClass}`;
          locatorName = camelCase(`${tag}_${firstClass}`);
        } else {
          return; // Skip elements without identifiable attributes
        }

        if (seen.has(bestSelector)) return;
        seen.add(bestSelector);

        const attrs: Record<string, string> = {};
        if (id) attrs.id = id;
        if (name) attrs.name = name;
        if (type) attrs.type = type;
        if (className) attrs.class = className;
        if (href) attrs.href = href;
        if (value) attrs.value = value;
        if (alt) attrs.alt = alt;
        if (role) attrs.role = role;

        results.push({
          name: locatorName || `${tag}_element`,
          selector: bestSelector,
          type: tag,
          text: text || undefined,
          attributes: attrs,
        });
      });
    }

    return results;

    function camelCase(str: string): string {
      return str
        .replace(/[^a-zA-Z0-9]+/g, " ")
        .trim()
        .split(" ")
        .map((word, i) =>
          i === 0
            ? word.toLowerCase()
            : word.charAt(0).toUpperCase() + word.slice(1).toLowerCase(),
        )
        .join("");
    }
  });
}

/** Generates a TypeScript locator file from extracted elements */
function generateLocatorFile(
  pageName: string,
  locators: ExtractedLocator[],
): string {
  const constName = `${pageName.toUpperCase()}_LOCATORS`;

  const entries = locators.map((loc) => {
    const comment = loc.text
      ? ` // ${loc.type}: "${loc.text}"`
      : ` // ${loc.type}`;
    return `  ${loc.name}: '${loc.selector.replace(/'/g, "\\'")}',${comment}`;
  });

  return `// Auto-generated by MCP Locator Extractor
// Page: ${pageName}
// Generated: ${new Date().toISOString()}
// Review and customize locators before use in tests.

export const ${constName} = {
${entries.join("\n")}
};
`;
}

/** Generates a Page Object class stub from extracted locators */
function generatePageObjectStub(
  pageName: string,
  locators: ExtractedLocator[],
): string {
  const className =
    pageName.charAt(0).toUpperCase() + pageName.slice(1) + "Page";
  const locatorImport = `${pageName.toUpperCase()}_LOCATORS`;
  const locatorFile = `./${pageName}.locators`;

  const methods = locators
    .filter((loc) => ["a", "button", "input", "select"].includes(loc.type))
    .slice(0, 30) // Limit to avoid huge files
    .map((loc) => {
      if (
        loc.type === "a" ||
        loc.type === "button" ||
        loc.attributes.role === "button"
      ) {
        return `
  async click${loc.name.charAt(0).toUpperCase() + loc.name.slice(1)}() {
    await this.page.locator(${locatorImport}.${loc.name}).click();
  }`;
      }
      if (loc.type === "input" && loc.attributes.type !== "submit") {
        return `
  async fill${loc.name.charAt(0).toUpperCase() + loc.name.slice(1)}(value: string) {
    await this.page.locator(${locatorImport}.${loc.name}).fill(value);
  }`;
      }
      if (loc.type === "select") {
        return `
  async select${loc.name.charAt(0).toUpperCase() + loc.name.slice(1)}(label: string) {
    await this.page.selectOption(${locatorImport}.${loc.name}, { label });
  }`;
      }
      return "";
    })
    .filter(Boolean);

  return `// Auto-generated Page Object stub by MCP Locator Extractor
// Review and customize before use.

import { Page, expect } from "@playwright/test";
import { ${locatorImport} } from "../locators/${locatorFile}";

export class ${className} {
  constructor(private page: Page) {}
${methods.join("\n")}
}
`;
}

async function main() {
  const args = process.argv.slice(2);
  const urlIdx = args.indexOf("--url");
  const outputIdx = args.indexOf("--output");

  if (urlIdx === -1) {
    console.error(
      "Usage: npx ts-node tools/mcpLocatorExtractor.ts --url <page-url> --output <name>",
    );
    process.exit(1);
  }

  const url = args[urlIdx + 1];
  const outputName = outputIdx !== -1 ? args[outputIdx + 1] : "extractedPage";

  console.log(`\n🔍 MCP Locator Extractor`);
  console.log(`   URL: ${url}`);
  console.log(`   Output: ${outputName}\n`);

  // Use stored auth state if available
  const authPath = path.resolve(process.cwd(), ".auth/storageState.json");
  const hasAuth = fs.existsSync(authPath);

  const browser = await chromium.launch({ headless: false });
  const context = hasAuth
    ? await browser.newContext({
        storageState: authPath,
        ignoreHTTPSErrors: true,
      })
    : await browser.newContext({ ignoreHTTPSErrors: true });

  const page = await context.newPage();

  console.log("📄 Navigating to page...");
  await page.goto(url, { waitUntil: "networkidle", timeout: 30000 });
  await page.waitForTimeout(2000); // Allow dynamic elements to render

  console.log("🔎 Extracting locators from DOM...");
  const locators = await extractLocatorsFromPage(page);
  console.log(`   Found ${locators.length} interactive elements.\n`);

  // Save raw JSON for AI processing
  const jsonDir = path.join("tools", "extracted");
  if (!fs.existsSync(jsonDir)) fs.mkdirSync(jsonDir, { recursive: true });

  const jsonPath = path.join(jsonDir, `${outputName}.locators.json`);
  fs.writeFileSync(jsonPath, JSON.stringify(locators, null, 2));
  console.log(`📋 Raw locators saved: ${jsonPath}`);

  // Generate TypeScript locator file
  const locatorContent = generateLocatorFile(outputName, locators);
  const locatorPath = path.join(
    "src",
    "locators",
    `${outputName}.extracted.locators.ts`,
  );
  fs.writeFileSync(locatorPath, locatorContent);
  console.log(`📝 Locator file generated: ${locatorPath}`);

  // Generate Page Object stub
  const pageObjectContent = generatePageObjectStub(outputName, locators);
  const pageObjectPath = path.join(
    "src",
    "pages",
    `${outputName}.extracted.page.ts`,
  );
  fs.writeFileSync(pageObjectPath, pageObjectContent);
  console.log(`🏗️  Page Object stub generated: ${pageObjectPath}`);

  // Take a screenshot for reference
  const screenshotPath = path.join(jsonDir, `${outputName}.screenshot.png`);
  await page.screenshot({ path: screenshotPath, fullPage: true });
  console.log(`📸 Screenshot saved: ${screenshotPath}`);

  await browser.close();

  console.log(
    `\n✅ Extraction complete! Review generated files and merge into your framework.`,
  );
}

main().catch((err) => {
  console.error("Extraction failed:", err);
  process.exit(1);
});
